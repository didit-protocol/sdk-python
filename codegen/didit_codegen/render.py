def docstring(text: str | None, indent: str) -> str:
    if not text:
        return ""
    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    if body.endswith('"'):
        body += " "
    lines = body.splitlines()
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    out = [f'{indent}"""{lines[0]}']
    for line in lines[1:]:
        out.append(f"{indent}{line}".rstrip())
    out.append(f'{indent}"""')
    return "\n".join(out) + "\n"


def module_path(module: str) -> str:
    return module.replace(".", "/") + ".py"


def _topo(names: list[str], registry: Registry) -> list[str]:
    local = set(names)
    order: list[str] = []
    state: dict[str, int] = {}

    def visit(name: str) -> None:
        if state.get(name) == 2:
            return
        if state.get(name) == 1:
            raise RuntimeError(f"Cycle between generated types at {name}.")
        state[name] = 1
        for dep in sorted(registry.defs[name].deps):
            if dep in local:
                visit(dep)
        state[name] = 2
        order.append(name)

    for name in names:
        visit(name)
    return order


# Types --------------------------------------------------------------------------


def render_types(registry: Registry) -> dict[str, str]:
    files: dict[str, str] = {}
    packages: set[str] = set()
    for module, names in registry.modules.items():
        parts = module.split(".")
        for i in range(1, len(parts)):
            packages.add(".".join(parts[:i]))
        files[module_path(module)] = _render_type_module(module, names, registry)
    for package in packages:
        files[package.replace(".", "/") + "/__init__.py"] = HEADER
    files["__init__.py"] = _render_types_init(registry)
    return files


def _imports_for(defs: list[TypeDef], registry: Registry, module: str) -> list[str]:
    deps: set[str] = set()
    kinds = {td.kind for td in defs}
    uses_field = False
    for td in defs:
        deps |= td.deps
        for f in td.fields:
            if td.kind == "model" and f.name != f.wire:
                uses_field = True
    lines: list[str] = ["from __future__ import annotations", ""]
    std: list[str] = []
    if DATETIME in deps or DATE in deps:
        std.append("import datetime as _dt")
    typing_names = sorted(
        n
        for n, marker in (("Literal", LITERAL), ("Mapping", MAPPING), ("Sequence", SEQUENCE))
        if marker in deps
    )
    if typing_names:
        std.append(f"from typing import {', '.join(typing_names)}")
    if std:
        lines.extend(std)
        lines.append("")
    third: list[str] = []
    if uses_field:
        third.append("from pydantic import Field")
    te: list[str] = []
    if "typeddict" in kinds:
        if any(f.required for td in defs if td.kind == "typeddict" for f in td.fields):
            te.append("Required")
        te.append("TypedDict")
    if "alias" in kinds:
        te.append("TypeAlias")
    if te:
        third.append(f"from typing_extensions import {', '.join(sorted(te))}")
    if third:
        lines.extend(third)
        lines.append("")
    first: list[str] = []
    if any(td.kind == "model" and not td.bases for td in defs):
        first.append("from didit._models import BaseModel")
    if FILE_TYPES in deps:
        first.append("from didit._types import FileTypes")
    local = {td.name for td in defs}
    by_module: dict[str, list[str]] = defaultdict(list)
    for dep in sorted(deps):
        if dep.startswith("@") or dep in local:
            continue
        target = registry.defs[dep]
        by_module[target.module].append(dep)
    for mod in sorted(by_module):
        first.append(f"from didit.types.{mod} import {', '.join(sorted(by_module[mod]))}")
    if first:
        lines.extend(first)
        lines.append("")
    return lines


def _render_type_module(module: str, names: list[str], registry: Registry) -> str:
    ordered = _topo(names, registry)
    defs = [registry.defs[n] for n in ordered]
    out = [HEADER]
    out.extend(line + "\n" for line in _imports_for(defs, registry, module))
    out.append("__all__ = [" + ", ".join(json.dumps(n) for n in sorted(names)) + "]\n\n")
    for td in defs:
        out.append("\n")
        out.append(_render_def(td))
    return "".join(out)


def _field_doc(description: str | None, deprecated: bool) -> str | None:
    text = description or ""
    if deprecated:
        text = ("Deprecated. " + text).strip()
    return text or None


def _render_def(td: TypeDef) -> str:
    if td.kind == "alias":
        assert td.alias is not None
        text = f"{td.name}: TypeAlias = {td.alias.expr}\n"
        doc = docstring(td.description, "")
        return text + doc
    if td.kind == "model":
        bases = ", ".join(td.bases) or "BaseModel"
        out = [f"class {td.name}({bases}):\n"]
        out.append(docstring(td.description, "    ") or "")
        if not td.fields and not td.description:
            out.append("    pass\n")
        for f in td.fields:
            ann = f.annotation.expr
            if f.name != f.wire:
                default = "default=None, " if not f.required else ""
                line = f"    {f.name}: {ann} = Field({default}alias={json.dumps(f.wire, ensure_ascii=False)})\n"
            elif not f.required:
                line = f"    {f.name}: {ann} = None\n"
            else:
                line = f"    {f.name}: {ann}\n"
            out.append("\n" if out[-1] != f"class {td.name}({bases}):\n" else "")
            out.append(line)
            out.append(docstring(_field_doc(f.description, f.deprecated), "    "))
        return "".join(out) + "\n"
    # TypedDict
    functional = any(
        not f.wire.isidentifier() or not f.wire.isascii() or _is_keyword(f.wire) for f in td.fields
    )
    if functional:
        if td.bases:
            raise RuntimeError(f"{td.name}: a functional TypedDict cannot have bases.")
        items = []
        for f in td.fields:
            ann = f"Required[{f.annotation.expr}]" if f.required else f.annotation.expr
            items.append(f"        {json.dumps(f.wire, ensure_ascii=False)}: {ann},\n")
        text = (
            f'{td.name} = TypedDict(\n    "{td.name}",\n    {{\n'
            + "".join(items)
            + "    },\n    total=False,\n)\n"
        )
        return text + docstring(td.description, "")
    bases = ", ".join(td.bases) if td.bases else "TypedDict"
    total = ", total=False"
    out = [f"class {td.name}({bases}{total}):\n"]
    out.append(docstring(td.description, "    ") or "")
    if not td.fields and not td.description:
        out.append("    pass\n")
    for f in td.fields:
        ann = f"Required[{f.annotation.expr}]" if f.required else f.annotation.expr
        if len(out) > 1:
            out.append("\n")
        out.append(f"    {f.wire}: {ann}\n")
        out.append(docstring(_field_doc(f.description, f.deprecated), "    "))
    return "".join(out) + "\n"


def _is_keyword(name: str) -> bool:
    import keyword

    return keyword.iskeyword(name)


def _render_types_init(registry: Registry) -> str:
    names = sorted(registry.defs)
    out = [HEADER, '"""Every request and response type of the Didit API.\n\n']
    out.append("Names follow docs/DESIGN.md section 5.1. Modules load on first use, so\n")
    out.append('``import didit`` stays fast.\n"""\n\n')
    out.append("from __future__ import annotations\n\n")
    out.append("import importlib\nfrom typing import TYPE_CHECKING, Any\n\n")
    out.append("if TYPE_CHECKING:\n")
    by_module: dict[str, list[str]] = defaultdict(list)
    for name in names:
        by_module[registry.defs[name].module].append(name)
    for mod in sorted(by_module):
        imported = ", ".join(f"{n} as {n}" for n in sorted(by_module[mod]))
        out.append(f"    from didit.types.{mod} import {imported}\n")
    out.append("\n_MODULES: dict[str, str] = {\n")
    for name in names:
        out.append(f'    "{name}": "{registry.defs[name].module}",\n')
    out.append("}\n\n")
    out.append("__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n\n\n")
    out.append(
        "def __getattr__(name: str) -> Any:\n"
        "    module = _MODULES.get(name)\n"
        "    if module is None:\n"
        '        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")\n'
        '    value = getattr(importlib.import_module(f"didit.types.{module}"), name)\n'
        "    globals()[name] = value\n"
        "    return value\n\n\n"
        "def __dir__() -> list[str]:\n"
        "    return __all__\n"
    )
    return "".join(out)


# Resources ------------------------------------------------------------------------


class ResourceNode:
    def __init__(self, path: str) -> None:
        self.path = path
        self.methods: list[Method] = []
        self.children: dict[str, ResourceNode] = {}

    @property
    def cls(self) -> str:
        return resource_class(self.path)

    @property
    def module(self) -> str:
        parts = self.path.split(".")
        if self.children:
            return "didit.resources." + ".".join(parts)
        return "didit.resources." + ".".join(parts)

    @property
    def file(self) -> str:
        parts = self.path.split(".")
        if self.children:
            return "/".join(parts) + "/__init__.py"
        return "/".join(parts) + ".py"


def build_tree(methods: list[Method]) -> dict[str, ResourceNode]:
    roots: dict[str, ResourceNode] = {}
    nodes: dict[str, ResourceNode] = {}
    for method in methods:
        parts = method.resource.split(".")
        for i in range(1, len(parts) + 1):
            path = ".".join(parts[:i])
            if path not in nodes:
                nodes[path] = ResourceNode(path)
                if i == 1:
                    roots[path] = nodes[path]
                else:
                    nodes[".".join(parts[: i - 1])].children[parts[i - 1]] = nodes[path]
        nodes[method.resource].methods.append(method)
    return roots


def all_nodes(roots: dict[str, ResourceNode]) -> list[ResourceNode]:
    out: list[ResourceNode] = []
    stack = list(roots.values())
    while stack:
        node = stack.pop()
        out.append(node)
        stack.extend(node.children.values())
    return sorted(out, key=lambda n: n.path)


def render_resources(roots: dict[str, ResourceNode], registry: Registry) -> dict[str, str]:
    files: dict[str, str] = {}
    for node in all_nodes(roots):
        files[node.file] = _render_resource(node, registry)
    files["__init__.py"] = _render_root(roots)
    return files


_SHADOWED = re.compile(r"(?<![\w.])(list|dict)\[")


def builtin_safe(expr: str) -> str:
    """Resource classes have methods named ``list``, so annotations there spell
    the builtins as ``builtins.list``."""
    return _SHADOWED.sub(lambda m: f"builtins.{m.group(1)}[", expr)


def _sig_args(method: Method) -> list[str]:
    args = ["self"]
    for arg in method.path_args:
        args.append(f"{arg.py}: str")
    args.append("*")
    if method.whole_body is not None:
        wb = method.whole_body
        if wb.required:
            args.append(f"{wb.py}: {builtin_safe(wb.annotation.expr)}")
        else:
            args.append(f"{wb.py}: {builtin_safe(wb.annotation.expr)} | NotGiven = NOT_GIVEN")
    for arg in method.kwargs:
        if arg.required:
            args.append(f"{arg.py}: {builtin_safe(arg.annotation.expr)}")
        else:
            args.append(f"{arg.py}: {builtin_safe(arg.annotation.expr)} | NotGiven = NOT_GIVEN")
    if method.idempotency:
        args.append("idempotency_key: str | NotGiven = NOT_GIVEN")
    args.extend(
        [
            "extra_headers: Headers | None = None",
            "extra_query: Query | None = None",
            "extra_body: Body | None = None",
            "timeout: float | httpx.Timeout | None | NotGiven = NOT_GIVEN",
        ]
    )
    return args


def _method_doc(method: Method) -> str:
    parts: list[str] = []
    if method.op.deprecated:
        parts.append(
            "Deprecated: "
            + (method.op.deprecation_note or "this operation is deprecated in the API contract.")
        )
    if method.summary:
        parts.append(method.summary.rstrip(".") + ".")
    if method.description and method.description != method.summary:
        parts.append(method.description)
    parts.append(f"``{method.op.http_method.upper()} {method.op.path}``")
    arg_lines: list[str] = []
    for arg in [
        *method.path_args,
        *([method.whole_body] if method.whole_body else []),
        *method.kwargs,
    ]:
        desc = (arg.description or "").strip()
        desc = " ".join(desc.split())
        arg_lines.append(f"  {arg.py}: {desc}" if desc else f"  {arg.py}")
    if method.idempotency:
        arg_lines.append(
            "  idempotency_key: Sent as the ``Idempotency-Key`` header; a retry with the same key "
            "returns the first result instead of acting twice."
        )
    arg_lines.extend(
        [
            "  extra_headers: Headers to add to (or, with ``None``, remove from) this request.",
            "  extra_query: Query parameters to add to this request.",
            "  extra_body: Top-level JSON fields to add to this request's body.",
            "  timeout: Overrides the client's timeout for this request, in seconds.",
        ]
    )
    parts.append("Args:\n" + "\n".join(arg_lines))
    return "\n\n".join(parts)


def _call(method: Method, is_async: bool) -> str:
    op = method.op
    lines: list[str] = []
    page = method.response.kind == "page"
    fn = "request_page" if page else "request"
    lines.append(f'"{op.http_method}"')
    lines.append(json.dumps(op.path))
    lines.append(f"cast_to={builtin_safe(method.response.cast_to)}")
    if method.response.kind == "page":
        assert method.response.item is not None
        lines.append(f"item_type={builtin_safe(method.response.item.expr)}")
    if method.path_args:
        pp = ", ".join(f"{json.dumps(a.wire)}: {a.py}" for a in method.path_args)
        lines.append(f"path_params={{{pp}}}")
    if op.sdk.scope:
        lines.append(f'scope="{op.sdk.scope}"')
    lines.append(f'auth="{op.sdk.auth}"')
    if op.api != "verification":
        lines.append(f'api="{op.api}"')
    query = [a for a in method.kwargs if a.location == "query"]
    if query:
        q = ", ".join(f"{json.dumps(a.wire)}: {a.py}" for a in query)
        lines.append(f"query={{{q}}}")
    body = [a for a in method.kwargs if a.location == "body"]
    if method.whole_body is not None:
        lines.append(f"body={method.whole_body.py}")
    elif method.body_mode != "none":
        b = ", ".join(f"{json.dumps(a.wire)}: {a.py}" for a in body)
        lines.append(f"body={{{b}}}")
    if method.body_mode == "multipart":
        lines.append("multipart=True")
    elif method.body_mode == "auto":
        lines.append('multipart="auto"')
    if method.file_fields:
        ff = ", ".join(json.dumps(f) for f in method.file_fields)
        lines.append(f"file_fields=({ff},)")
    if method.idempotency:
        lines.append('headers={"Idempotency-Key": idempotency_key}')
    if method.response.accept != "application/json":
        lines.append(f"accept={json.dumps(method.response.accept)}")
    lines.extend(
        [
            "extra_headers=extra_headers",
            "extra_query=extra_query",
            "extra_body=extra_body",
            "timeout=timeout",
        ]
    )
    inner = ",\n                ".join(lines)
    awaited = "await " if is_async and not page else ""
    return_type = _return_type(method, is_async)
    return (
        f"        return cast(\n"
        f'            "{return_type}",\n'
        f"            {awaited}self._client.{fn}(\n"
        f"                {inner},\n"
        f"            ),\n"
        f"        )\n"
    )


def _return_type(method: Method, is_async: bool) -> str:
    if method.response.kind == "page":
        assert method.response.item is not None
        wrapper = "AsyncPaginator" if is_async else "SyncPage"
        return f"{wrapper}[{builtin_safe(method.response.item.expr)}]"
    return builtin_safe(method.response.annotation.expr)


def _render_method(method: Method, is_async: bool) -> str:
    page = method.response.kind == "page"
    kw = "async def" if is_async and not page else "def"
    out: list[str] = []
    if method.op.deprecated:
        note = method.op.deprecation_note or "This operation is deprecated in the API contract."
        out.append(f"    @deprecated({json.dumps(note)})\n")
    args = ",\n        ".join(_sig_args(method))
    out.append(
        f"    {kw} {method.name}(\n        {args},\n    ) -> {_return_type(method, is_async)}:\n"
    )
    out.append(docstring(_method_doc(method), "        "))
    out.append(_call(method, is_async))
    return "".join(out)


def _render_resource(node: ResourceNode, registry: Registry) -> str:
    deps: set[str] = set()
    for method in node.methods:
        deps |= method.deps
    has_page = any(m.response.kind == "page" for m in node.methods)
    has_deprecated = any(m.op.deprecated for m in node.methods)
    out: list[str] = [HEADER]
    doc = f"The ``{node.path}`` resource."
    out.append(f'"""{doc}"""\n\n')
    out.append("from __future__ import annotations\n\n")
    std = []
    if deps & {DATETIME, DATE}:
        std.append("import datetime as _dt")
    std.append("from functools import cached_property")
    has_methods = bool(node.methods)
    typing_names = (["TYPE_CHECKING"] if node.children else []) + (["cast"] if has_methods else [])
    typing_names += [
        n
        for n, m in (("Literal", LITERAL), ("Mapping", MAPPING), ("Sequence", SEQUENCE))
        if m in deps
    ]
    if typing_names:
        std.append(
            f"from typing import {', '.join(sorted(typing_names, key=lambda s: (s != 'TYPE_CHECKING', s.lower())))}"
        )
    out.append("\n".join(std) + "\n\n")
    if has_methods:
        out.append("import httpx\n")
    if has_deprecated:
        out.append("from typing_extensions import deprecated\n")
    if has_methods or has_deprecated:
        out.append("\n")
    first = []
    if has_page:
        first.append("from didit._pagination import AsyncPaginator, SyncPage")
    first.append("from didit._resource import AsyncAPIResource, SyncAPIResource")
    if has_methods:
        first.append(
            "from didit._response import (\n"
            "    async_to_raw_response_wrapper,\n"
            "    async_to_streamed_response_wrapper,\n"
            "    to_raw_response_wrapper,\n"
            "    to_streamed_response_wrapper,\n"
            ")"
        )
        types_names = ["NOT_GIVEN", "Body", "Headers", "NotGiven", "Query"]
        if FILE_TYPES in deps:
            types_names.append("FileTypes")
        first.append(
            f"from didit._types import {', '.join(sorted(types_names, key=lambda s: (not s.isupper(), s)))}"
        )
    mixin = RESOURCE_MIXINS.get(node.path)
    if mixin:
        first.append(f"from {mixin[0]} import {mixin[1]}")
    by_module: dict[str, list[str]] = defaultdict(list)
    for dep in sorted(deps):
        if dep.startswith("@"):
            continue
        by_module[registry.defs[dep].module].append(dep)
    for mod in sorted(by_module):
        first.append(f"from didit.types.{mod} import {', '.join(sorted(by_module[mod]))}")
    out.append("\n".join(first) + "\n\n")
    children = sorted(node.children.items())
    if children:
        out.append("if TYPE_CHECKING:\n")
        for _, child in children:
            c = child.cls
            out.append(
                f"    from {child.module} import (\n"
                f"        Async{c},\n"
                f"        Async{c}WithRawResponse,\n"
                f"        Async{c}WithStreamingResponse,\n"
                f"        {c},\n"
                f"        {c}WithRawResponse,\n"
                f"        {c}WithStreamingResponse,\n"
                f"    )\n"
            )
        out.append("\n")
    cls = node.cls
    all_names = [cls, f"Async{cls}", f"{cls}WithRawResponse", f"Async{cls}WithRawResponse",
                 f"{cls}WithStreamingResponse", f"Async{cls}WithStreamingResponse"]  # fmt: skip
    out.append("__all__ = [" + ", ".join(json.dumps(n) for n in all_names) + "]\n\n")

    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        base = "AsyncAPIResource" if is_async else "SyncAPIResource"
        bases = f"{mixin[1]}, {base}" if mixin else base
        out.append(f"\nclass {prefix}{cls}({bases}):\n")
        out.append(docstring(_resource_doc(node), "    "))
        for name, child in children:
            out.append("\n    @cached_property\n")
            out.append(f"    def {name}(self) -> {prefix}{child.cls}:\n")
            out.append(f"        from {child.module} import {prefix}{child.cls}\n\n")
            out.append(f"        return {prefix}{child.cls}(self._client)\n")
        for kind in ("RawResponse", "StreamingResponse"):
            attr = "with_raw_response" if kind == "RawResponse" else "with_streaming_response"
            out.append("\n    @cached_property\n")
            out.append(f"    def {attr}(self) -> {prefix}{cls}With{kind}:\n")
            what = (
                "the raw HTTP response"
                if kind == "RawResponse"
                else "the HTTP response before reading its body"
            )
            out.append(f'        """Every method of this resource, returning {what}."""\n')
            out.append(f"        return {prefix}{cls}With{kind}(self)\n")
        for method in node.methods:
            out.append("\n")
            out.append(_render_method(method, is_async))
        out.append("\n")

    for kind in ("RawResponse", "StreamingResponse"):
        for is_async in (False, True):
            prefix = "Async" if is_async else ""
            wrapper = {
                ("RawResponse", False): "to_raw_response_wrapper",
                ("RawResponse", True): "async_to_raw_response_wrapper",
                ("StreamingResponse", False): "to_streamed_response_wrapper",
                ("StreamingResponse", True): "async_to_streamed_response_wrapper",
            }[(kind, is_async)]
            out.append(f"\nclass {prefix}{cls}With{kind}:\n")
            out.append(f"    def __init__(self, resource: {prefix}{cls}) -> None:\n")
            out.append("        self._resource = resource\n")
            for method in node.methods:
                out.append(f"        self.{method.name} = {wrapper}(resource.{method.name})\n")
            for name, child in children:
                out.append("\n    @cached_property\n")
                out.append(f"    def {name}(self) -> {prefix}{child.cls}With{kind}:\n")
                out.append(f"        from {child.module} import {prefix}{child.cls}With{kind}\n\n")
                out.append(f"        return {prefix}{child.cls}With{kind}(self._resource.{name})\n")
            out.append("\n")
    text = "".join(out)
    if "builtins." in text:
        text = text.replace("from __future__ import annotations\n\n", "from __future__ import annotations\n\nimport builtins\n", 1)
    return text


def _resource_doc(node: ResourceNode) -> str:
    ops = sorted(m.name for m in node.methods)
    subs = sorted(node.children)
    text = f"The ``{node.path}`` resource of the Didit API."
    if ops:
        text += "\n\nMethods: " + ", ".join(f"``{m}``" for m in ops) + "."
    if subs:
        text += "\n\nNested resources: " + ", ".join(f"``{s}``" for s in subs) + "."
    return text


def _render_root(roots: dict[str, ResourceNode]) -> str:
    out = [HEADER, '"""The resource tree of the Didit API (docs/DESIGN.md section 4)."""\n\n']
    out.append("from __future__ import annotations\n\n")
    out.append("from functools import cached_property\nfrom typing import TYPE_CHECKING\n\n")
    out.append("from didit._base_client import AsyncAPIClient, SyncAPIClient\n\n")
    out.append("if TYPE_CHECKING:\n")
    for node in sorted(roots.values(), key=lambda n: n.path):
        out.append(f"    from {node.module} import Async{node.cls}, {node.cls}\n")
    out.append('\n__all__ = ["AsyncRootResources", "SyncRootResources"]\n\n')
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        base = "AsyncAPIClient" if is_async else "SyncAPIClient"
        out.append(
            f"\nclass {prefix}{'RootResources' if is_async else 'SyncRootResources'}({base}):\n"
        )
        out.append('    """Top-level resources, loaded on first use."""\n')
        for name, node in sorted(roots.items()):
            out.append("\n    @cached_property\n")
            out.append(f"    def {name}(self) -> {prefix}{node.cls}:\n")
            out.append(f"        from {node.module} import {prefix}{node.cls}\n\n")
            out.append(f"        return {prefix}{node.cls}(self)\n")
        out.append("\n")
    return "".join(out)
